import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('contorno editável, trena, aparência e localização com carregamento', async ({ page }) => {
  test.setTimeout(90_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    navigator.geolocation.getCurrentPosition = success => setTimeout(() => success({ coords: { latitude: -15.17862, longitude: -47.92232, altitude: null } }), 350);
  });
  await page.goto('/');
  await expect(page.locator('#tool-outline')).toBeEnabled({ timeout: 35_000 });
  await page.getByRole('button', { name: '2D', exact: true }).click();
  await expect(page.locator('#view-2d')).toHaveAttribute('aria-pressed', 'true');
  const canvas = await page.locator('.maplibregl-canvas').boundingBox(), x = canvas.x + canvas.width / 2, y = canvas.y + canvas.height / 2;
  const original = await page.locator('#coordinates').textContent();
  await page.locator('#tool-outline').click();
  for (const [dx, dy] of [[-80, -80], [80, -80], [80, 80], [-80, 80]]) await page.mouse.click(x + dx, y + dy);
  await page.locator('#close-outline').click();
  await expect(page.locator('#outline-result')).toContainText('4 pontos');
  await expect(page.locator('#coordinates')).toHaveText(original);
  const before = await page.locator('#outline-result').textContent();
  await page.locator('#tool-outline').click();
  await page.mouse.move(x - 80, y - 80); await page.mouse.down(); await page.mouse.move(x - 120, y - 100, { steps: 6 }); await page.mouse.up();
  await expect(page.locator('#outline-result')).not.toHaveText(before);
  await page.locator('#tool-measure').click();
  await page.mouse.click(x - 60, y + 120); await page.mouse.click(x + 90, y + 120);
  await expect(page.locator('#measure-result')).not.toHaveText('Trena: 0,00 m');
  await page.locator('#map-intensity').fill('35');
  await expect(page.locator('#map-intensity-value')).toHaveText('35%');
  await page.locator('#color-land').fill('#cccccc');
  await page.locator('#color-land').dispatchEvent('input');
  await page.screenshot({ path: process.env.USERPROFILE + '/.tools/kobb-atlas/atlas-sketch.png', fullPage: true });
  await page.locator('#export-button').click(); await page.locator('#export-format').selectOption('json');
  const pending = page.waitForEvent('download'); await page.locator('#export-save').click();
  const download = await pending, report = JSON.parse(await readFile(await download.path(), 'utf-8'));
  expect(report.annotations.outline).toHaveLength(4); expect(report.annotations.closed).toBe(true);
  expect(report.annotations.measurement).toHaveLength(2); expect(report.annotations.horizontalMeters).toBeGreaterThan(20);
  await page.locator('#export-button').click(); await page.locator('#export-format').selectOption('dxf');
  const cadPending = page.waitForEvent('download'); await page.locator('#export-save').click();
  const cad = await cadPending;
  const drawing = await readFile(await cad.path(), 'utf-8');
  expect(drawing).toContain('ATLAS_TERRAIN'); expect(drawing).toContain('ATLAS_MEASURE');
  await cad.saveAs(process.env.USERPROFILE + '/.tools/kobb-atlas/atlas-sketch.dxf');
  await page.locator('#basemap').selectOption('satellite');
  await expect(page.locator('#map-intensity')).toBeDisabled(); await expect(page.locator('#color-land')).toBeDisabled();
  await page.locator('#basemap').selectOption('street'); await expect(page.locator('#map-intensity')).toBeEnabled();
  await page.locator('#reset-appearance').click(); await expect(page.locator('#map-intensity-value')).toHaveText('100%');
  await page.reload(); await expect(page.locator('#outline-result')).toContainText('4 pontos');
  await page.locator('#locate').click();
  await expect(page.locator('#locate')).toHaveAttribute('aria-busy', 'true'); await expect(page.locator('#locate .locating-spinner')).toBeVisible();
  await expect(page.locator('#coordinates')).toContainText('15,17862');
  await expect(page.locator('#locate')).toHaveAttribute('aria-busy', 'false'); await expect(page.locator('#locate')).toBeEnabled();
  await page.evaluate(() => { navigator.geolocation.getCurrentPosition = (_, failure) => setTimeout(() => failure({ code: 1 }), 200); });
  await page.locator('#locate').click(); await expect(page.locator('#locate')).toHaveAttribute('aria-busy', 'true');
  await expect(page.locator('#locate')).toHaveAttribute('aria-busy', 'false'); await expect(page.locator('#locate .locating-spinner')).toHaveCount(0);
  expect(errors).toEqual([]);
});
